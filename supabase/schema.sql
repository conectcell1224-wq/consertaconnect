-- ---------- 0. Tipos ----------
do $$ begin
  create type public.status_os as enum
    ('aguardando','em_analise','aguardando_peca','em_reparo','pronto','entregue','cancelado');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.prioridade_os as enum ('baixa','normal','alta','urgente');
exception when duplicate_object then null; end $$;

-- ---------- 1. PROFILES (técnicos/usuários) ----------
create table if not exists public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  nome          text not null,
  telefone      text,
  email         text,
  avatar_url    text,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select to authenticated using (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
  for insert to authenticated with check (auth.uid() = id);

-- Cria profile no cadastro
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nome, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', split_part(new.email,'@',1)),
    new.email
  )
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- 2. CLIENTES ----------
create table if not exists public.clientes (
  id        uuid primary key default gen_random_uuid(),
  user_id   uuid not null references auth.users(id) on delete cascade,
  nome      text not null,
  telefone  text,
  email     text,
  cpf_cnpj  text,
  endereco  text,
  obs       text,
  criado_em timestamptz not null default now()
);

alter table public.clientes enable row level security;
create index if not exists clientes_user_idx on public.clientes(user_id);
create index if not exists clientes_nome_idx on public.clientes using gin (to_tsvector('portuguese', nome));

drop policy if exists "clientes_own" on public.clientes;
create policy "clientes_own" on public.clientes
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ---------- 3. ORDENS DE SERVIÇO ----------
create table if not exists public.ordens (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid not null references auth.users(id) on delete cascade,
  numero         bigint generated by default as identity,
  cliente_id     uuid references public.clientes(id) on delete set null,
  aparelho       text not null,
  marca          text,
  modelo         text,
  imei           text,
  defeito        text,
  diagnostico    text,
  solucao        text,
  status         public.status_os not null default 'aguardando',
  prioridade     public.prioridade_os not null default 'normal',
  valor_pecas    numeric(10,2) not null default 0,
  valor_mao_obra numeric(10,2) not null default 0,
  valor_total    numeric(10,2) generated always as (valor_pecas + valor_mao_obra) stored,
  entrada_em     timestamptz not null default now(),
  previsao_em    date,
  entregue_em    timestamptz,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);

alter table public.ordens enable row level security;
create index if not exists ordens_user_idx on public.ordens(user_id);
create index if not exists ordens_status_idx on public.ordens(status);
create index if not exists ordens_cliente_idx on public.ordens(cliente_id);

drop policy if exists "ordens_own" on public.ordens;
create policy "ordens_own" on public.ordens
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Atualiza atualizado_em automaticamente
create or replace function public.touch_atualizado_em()
returns trigger language plpgsql as $$
begin new.atualizado_em = now(); return new; end; $$;

drop trigger if exists ordens_touch on public.ordens;
create trigger ordens_touch before update on public.ordens
  for each row execute function public.touch_atualizado_em();

-- ---------- 4. ITENS DA OS (peças/serviços) ----------
create table if not exists public.os_itens (
  id        uuid primary key default gen_random_uuid(),
  os_id     uuid not null references public.ordens(id) on delete cascade,
  descricao text not null,
  qtd       numeric(10,2) not null default 1,
  valor_unit numeric(10,2) not null default 0,
  criado_em timestamptz not null default now()
);

alter table public.os_itens enable row level security;
create index if not exists os_itens_os_idx on public.os_itens(os_id);

drop policy if exists "os_itens_own" on public.os_itens;
create policy "os_itens_own" on public.os_itens
  for all to authenticated
  using (exists (select 1 from public.ordens o where o.id = os_id and o.user_id = auth.uid()))
  with check (exists (select 1 from public.ordens o where o.id = os_id and o.user_id = auth.uid()));

-- ---------- 5. HISTÓRICO (timeline da OS) ----------
create table if not exists public.os_historico (
  id        uuid primary key default gen_random_uuid(),
  os_id     uuid not null references public.ordens(id) on delete cascade,
  user_id   uuid references auth.users(id) on delete set null,
  status    public.status_os,
  nota      text,
  criado_em timestamptz not null default now()
);

alter table public.os_historico enable row level security;
create index if not exists os_hist_os_idx on public.os_historico(os_id);

drop policy if exists "os_historico_own" on public.os_historico;
create policy "os_historico_own" on public.os_historico
  for all to authenticated
  using (exists (select 1 from public.ordens o where o.id = os_id and o.user_id = auth.uid()))
  with check (exists (select 1 from public.ordens o where o.id = os_id and o.user_id = auth.uid()));

-- Registra mudança de status automaticamente
create or replace function public.log_status_os()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if (tg_op = 'INSERT') then
    insert into public.os_historico (os_id, user_id, status, nota)
    values (new.id, new.user_id, new.status, 'OS aberta');
  elsif (new.status is distinct from old.status) then
    insert into public.os_historico (os_id, user_id, status, nota)
    values (new.id, new.user_id, new.status, 'Status alterado de ' || old.status || ' para ' || new.status);
  end if;
  return new;
end; $$;

drop trigger if exists ordens_log_status on public.ordens;
create trigger ordens_log_status
  after insert or update of status on public.ordens
  for each row execute function public.log_status_os();

